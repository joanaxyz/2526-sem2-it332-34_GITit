"""Where a repository stands along an authored solution route.

A variant's ``solution_trajectory`` is generated by replaying its authored
solution through the browser Git engine (``generate_targets``, or the authoring
editor for authored content) and fingerprinting the state in front of every
solution command. At runtime the learner's repository is fingerprinted the same
way, so the backend can tell which solution step the learner is standing at
without a Python Git interpreter.

Fingerprints describe the *meaning* of a repository, not its bookkeeping:

- commits are identified by their tree and ancestry, never by generated ids,
  messages, or timestamps, so a learner's own commit message still matches;
- status spellings are canonicalized ("changed" and "modified" are the same);
- ``last_*`` operation metadata, reflog, and presentation-only keys are ignored.

Two strengths are stored. ``exact`` includes file contents; ``coarse`` keeps
only paths and statuses, so a learner who resolved a conflict with slightly
different text is still recognized as being at the same step.
"""

from __future__ import annotations

import hashlib
import json
from collections import Counter
from collections.abc import Iterable

from simulator.state import DISPLAY_STATUS_ALIASES, RepositoryStateNormalizer

TRAJECTORY_VERSION = 2
FINGERPRINT_STRENGTHS = ("exact", "coarse")
_DIGEST_LENGTH = 16


def _digest(value: object) -> str:
    encoded = json.dumps(value, sort_keys=True, separators=(",", ":"), default=str)
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()[:_DIGEST_LENGTH]


class RepositoryFingerprinter:
    """Canonical, id-independent description of a repository state."""

    def __init__(self) -> None:
        self.normalizer = RepositoryStateNormalizer()

    def fingerprints(self, state: dict) -> dict[str, str]:
        normalized = self.normalizer.normalize(state)
        return {
            strength: _digest(self.signature(normalized, exact=strength == "exact"))
            for strength in FINGERPRINT_STRENGTHS
        }

    def signature(self, state: dict, *, exact: bool) -> dict:
        commits = _CommitIdentities(state, exact=exact)
        head = state.get("head") or {}
        if head.get("type") == "branch":
            head_signature = {"branch": head.get("name")}
        else:
            head_signature = {"detached": commits.identity(head.get("target"))}
        return {
            "initialized": bool(state.get("repository_initialized", True)),
            "head": head_signature,
            "branches": {name: commits.identity(target) for name, target in _mapping(state, "branches")},
            "tags": {name: commits.identity(_ref_target(target)) for name, target in _mapping(state, "tags")},
            "remote_branches": {
                name: commits.identity(_ref_target(target))
                for name, target in _mapping(state, "remote_branches")
            },
            "remote_tags": sorted(name for name, _ in _mapping(state, "remote_tags")),
            "remotes": {
                name: (url if exact else None) for name, url in _mapping(state, "remotes")
            },
            "upstream_tracking": dict(_mapping(state, "upstream_tracking")),
            "config": {
                key: (value if exact else None) for key, value in _mapping(state, "config")
            },
            "staging": self._entries(state.get("staging"), exact=exact),
            "working_tree": self._entries(state.get("working_tree"), exact=exact),
            "conflicts": sorted(_paths(state.get("conflicts"))),
            "partial_hunks": sorted(_mapping_keys(state.get("partial_hunks"))),
            "stash": len(state.get("stash_stack") or []),
            "in_progress": in_progress_operations(state),
        }

    def _entries(self, entries: object, *, exact: bool) -> dict:
        if not isinstance(entries, dict):
            return {}
        signature = {}
        for path, value in entries.items():
            status = entry_status_class(value)
            if exact:
                # A bare status marker ("changed") carries no content of its own.
                is_marker = isinstance(value, str) and value.lower() in DISPLAY_STATUS_ALIASES
                content = None if is_marker else self.normalizer.entry_content(value)
                signature[str(path)] = [status, _digest(content)]
            else:
                signature[str(path)] = status
        return signature


class _CommitIdentities:
    """Logical commit identity: content tree plus the identities of parents."""

    def __init__(self, state: dict, *, exact: bool) -> None:
        self.exact = exact
        self.by_id = {
            str(commit.get("id")): commit
            for commit in state.get("commits") or []
            if isinstance(commit, dict) and commit.get("id") is not None
        }
        self.cache: dict[str, str] = {}

    def identity(self, commit_id: object) -> str | None:
        if commit_id is None:
            return None
        key = str(commit_id)
        if key in self.cache:
            return self.cache[key]
        commit = self.by_id.get(key)
        if commit is None:
            # Unknown ids (e.g. remote-only fixtures) still compare by name so a
            # ref pointing at them keeps a stable, if opaque, identity.
            return f"?{key}"
        # Iterative post-order walk: long histories must not hit recursion limits.
        stack = [key]
        while stack:
            current = stack[-1]
            if current in self.cache:
                stack.pop()
                continue
            parents = [str(parent) for parent in self.by_id[current].get("parents") or []]
            pending = [parent for parent in parents if parent in self.by_id and parent not in self.cache]
            if pending:
                stack.extend(pending)
                continue
            stack.pop()
            commit = self.by_id[current]
            tree = commit.get("tree") or {}
            # Exact identity keeps the message so rewording (amend) is a real
            # step; coarse identity tolerates the learner's own wording.
            content = [tree, str(commit.get("message") or "").strip()] if self.exact else sorted(tree)
            self.cache[current] = _digest(
                [content, [self.cache.get(parent, f"?{parent}") for parent in parents]]
            )
        return self.cache[key]


def entry_status_class(value: object) -> str:
    """Collapse the many authored/engine spellings of a file entry's status."""

    if isinstance(value, dict):
        raw = value.get("status") or value.get("state") or value.get("change_type")
        if raw is None:
            if value.get("ignored") is True:
                return "ignored"
            if value.get("untracked") is True:
                return "untracked"
            return "modified"
        return DISPLAY_STATUS_ALIASES.get(str(raw).lower(), str(raw).lower())
    # A bare string is either a status marker or the file content itself.
    return DISPLAY_STATUS_ALIASES.get(str(value or "").lower(), "modified")


def in_progress_operations(state: dict) -> list[str]:
    operations = []
    if state.get("merge_parent") or state.get("conflict_on_merge") or state.get("merge_abort_state"):
        operations.append("merge")
    if state.get("cherry_pick_in_progress"):
        operations.append("cherry-pick")
    if state.get("rebase_state"):
        operations.append("rebase")
    return operations


def _mapping(state: dict, key: str) -> list[tuple[str, object]]:
    value = state.get(key)
    if not isinstance(value, dict):
        return []
    return sorted((str(name), item) for name, item in value.items())


def _mapping_keys(value: object) -> list[str]:
    return [str(key) for key in value] if isinstance(value, dict) else []


def _paths(value: object) -> Iterable[str]:
    for item in value or []:
        if isinstance(item, dict):
            path = item.get("path") or item.get("file")
            if path:
                yield str(path)
        elif item:
            yield str(item)


def _ref_target(value: object) -> object:
    if isinstance(value, dict):
        return value.get("target") or value.get("commit") or value.get("id")
    return value


# --- change descriptions ------------------------------------------------------


def describe_transition(before: dict, after: dict) -> list[dict]:
    """What changed between two repository states, one entry per change.

    ``kind`` names the part of the repository that changed (``repository``,
    ``commit``, ``branch``, ``head``, ``staging``, ``working_tree``,
    ``conflict``, ``tag``, ``remote``, ``config``, ``stash``, ``operation``),
    ``action`` what happened to it (``create``, ``delete``, ``move``, ``add``,
    ``remove``, ``set``, ``start``, ``finish``), and ``subjects`` the files or
    names involved, so a client can draw the change without parsing ``text``.
    ``ref`` names the branch a new commit lands on.
    """

    normalizer = RepositoryStateNormalizer()
    before = normalizer.normalize(before)
    after = normalizer.normalize(after)
    changes: list[dict] = []

    def add(kind: str, text: str, action: str, subjects=(), ref: str | None = None) -> None:
        change = {"kind": kind, "text": text, "action": action, "subjects": sorted(subjects)}
        if ref:
            change["ref"] = ref
        changes.append(change)

    if not before.get("repository_initialized", True) and after.get("repository_initialized", True):
        add("repository", "The folder becomes a Git repository.", "create")

    before_ids = {commit.get("id") for commit in before.get("commits") or []}
    new_commits = [commit for commit in after.get("commits") or [] if commit.get("id") not in before_ids]
    head_branch = normalizer.head_branch(after)
    before_staged = set(_mapping_keys(before.get("staging")))
    after_staged = set(_mapping_keys(after.get("staging")))
    committed_paths = before_staged - after_staged if new_commits else set()
    if new_commits:
        where = f" on {head_branch}" if head_branch else ""
        subject = "New commit" if len(new_commits) == 1 else f"{len(new_commits)} new commits"
        saved = f", saving {_join(committed_paths)}" if committed_paths else ""
        add("commit", f"{subject}{where}{saved}.", "create", committed_paths, head_branch)

    before_branches = dict(_mapping(before, "branches"))
    after_branches = dict(_mapping(after, "branches"))
    for name in sorted(set(after_branches) - set(before_branches)):
        add("branch", f"Branch {name} is created.", "create", [name])
    for name in sorted(set(before_branches) - set(after_branches)):
        add("branch", f"Branch {name} is deleted.", "delete", [name])
    for name in sorted(set(before_branches) & set(after_branches)):
        if before_branches[name] != after_branches[name] and not (new_commits and name == head_branch):
            add("branch", f"Branch {name} moves to another commit.", "move", [name])

    before_head, after_head = before.get("head") or {}, after.get("head") or {}
    if (before_head.get("type"), before_head.get("name")) != (after_head.get("type"), after_head.get("name")):
        if after_head.get("type") == "branch":
            add("head", f"HEAD moves to {after_head.get('name')}.", "move", [after_head.get("name")])
        else:
            add("head", "HEAD is detached at a commit.", "move")
    elif after_head.get("type") != "branch" and before_head.get("target") != after_head.get("target"):
        add("head", "The detached HEAD moves to another commit.", "move")

    before_working = set(_mapping_keys(before.get("working_tree")))
    after_working = set(_mapping_keys(after.get("working_tree")))
    newly_staged = after_staged - before_staged
    unstaged = before_staged - after_staged - committed_paths
    if newly_staged:
        add("staging", f"{_join(newly_staged)} {_verb(newly_staged, 'is', 'are')} staged.", "add", newly_staged)
    if unstaged:
        add("staging", f"{_join(unstaged)} {_verb(unstaged, 'is', 'are')} unstaged.", "remove", unstaged)
    # Staging moves a file out of the working tree; that is one change, not two.
    new_edits = after_working - before_working - unstaged
    cleaned = before_working - after_working - newly_staged
    if new_edits:
        add("working_tree", f"{_join(new_edits)} {_verb(new_edits, 'has', 'have')} uncommitted edits.", "add",
            new_edits)
    if cleaned:
        add("working_tree", f"Edits to {_join(cleaned)} are discarded or saved elsewhere.", "remove", cleaned)

    before_conflicts, after_conflicts = set(_paths(before.get("conflicts"))), set(_paths(after.get("conflicts")))
    if after_conflicts - before_conflicts:
        opened = after_conflicts - before_conflicts
        add("conflict", f"Conflict to resolve in {_join(opened)}.", "add", opened)
    if before_conflicts - after_conflicts:
        resolved = before_conflicts - after_conflicts
        add("conflict", f"Conflict resolved in {_join(resolved)}.", "remove", resolved)

    _describe_names(add, before, after, "tags", "tag", "Tag {name} is created.", "Tag {name} is deleted.")
    _describe_names(add, before, after, "remotes", "remote", "Remote {name} is added.", "Remote {name} is removed.")
    before_remote, after_remote = dict(_mapping(before, "remote_branches")), dict(_mapping(after, "remote_branches"))
    updated = sorted(
        name for name in after_remote if name not in before_remote or before_remote[name] != after_remote[name]
    )
    if updated:
        add("remote", f"{_join(updated)} {_verb(updated, 'is', 'are')} updated.", "move", updated)
    removed_remote = sorted(set(before_remote) - set(after_remote))
    if removed_remote:
        add("remote", f"{_join(removed_remote)} {_verb(removed_remote, 'is', 'are')} removed.", "delete",
            removed_remote)

    before_config, after_config = dict(_mapping(before, "config")), dict(_mapping(after, "config"))
    for key in sorted(after_config):
        if before_config.get(key) != after_config[key]:
            add("config", f"{key} is set.", "set", [key])

    before_stash, after_stash = len(before.get("stash_stack") or []), len(after.get("stash_stack") or [])
    if after_stash > before_stash:
        add("stash", "Work is set aside in the stash.", "add")
    elif after_stash < before_stash:
        add("stash", "A stash entry is applied or dropped.", "remove")

    before_ops, after_ops = set(in_progress_operations(before)), set(in_progress_operations(after))
    for operation in sorted(after_ops - before_ops):
        add("operation", f"A {operation} is in progress.", "start", [operation])
    for operation in sorted(before_ops - after_ops):
        add("operation", f"The {operation} is finished.", "finish", [operation])
    return changes


def _describe_names(add, before, after, key, kind, added: str, removed: str) -> None:
    before_names, after_names = set(dict(_mapping(before, key))), set(dict(_mapping(after, key)))
    for name in sorted(after_names - before_names):
        add(kind, added.format(name=name), "create", [name])
    for name in sorted(before_names - after_names):
        add(kind, removed.format(name=name), "delete", [name])


def _join(items: Iterable[str]) -> str:
    ordered = sorted(items)
    if len(ordered) > 4:
        return f"{', '.join(ordered[:3])} and {len(ordered) - 3} more"
    return ordered[0] if len(ordered) == 1 else f"{', '.join(ordered[:-1])} and {ordered[-1]}"


def _verb(items, singular: str, plural: str) -> str:
    return singular if len(items) == 1 else plural


# --- trajectories ---------------------------------------------------------------


def build_solution_trajectory(replay: dict) -> dict:
    """Compact trajectory from a replay emitted by the browser engine.

    ``replay`` is ``{"steps": [...], "final": state}`` where each step holds the
    ``command``, the engine's ``diagnostic`` flag, the ``ready`` state the
    command runs against, and ``before_edits`` when authored file edits were
    applied just before it (the learner may not have made them yet).
    """

    fingerprinter = RepositoryFingerprinter()
    steps = replay.get("steps") or []
    final_state = replay.get("final") or {}
    trajectory_steps = []
    for index, step in enumerate(steps):
        ready = step.get("ready") or {}
        after = (
            (steps[index + 1].get("before_edits") or steps[index + 1].get("ready"))
            if index + 1 < len(steps)
            else replay.get("final_before_edits") or final_state
        )
        positions = [fingerprinter.fingerprints(ready)]
        if step.get("before_edits"):
            positions.insert(0, fingerprinter.fingerprints(step["before_edits"]))
        trajectory_steps.append(
            {
                "command": str(step.get("command") or ""),
                "diagnostic": bool(step.get("diagnostic")),
                "effect": [] if step.get("diagnostic") else describe_transition(ready, after or {}),
                "positions": positions,
            }
        )
    return {
        "version": TRAJECTORY_VERSION,
        "steps": trajectory_steps,
        "final": fingerprinter.fingerprints(final_state),
    }


def route_position(trajectory: dict | None, state: dict, history: Iterable[str] = ()) -> int | None:
    """Index of the solution step the repository stands in front of.

    ``len(steps)`` means the route is finished. ``None`` means the trajectory is
    missing or stale, or the repository is not on the authored route - callers
    must then stay silent rather than guess from an unrelated state.

    ``history`` (the learner's executed commands) resolves routes that revisit
    a state, such as detaching HEAD to inspect and switching back.
    """

    if not isinstance(trajectory, dict) or trajectory.get("version") != TRAJECTORY_VERSION:
        return None
    steps = trajectory.get("steps") or []
    if not steps:
        return None
    current = RepositoryFingerprinter().fingerprints(state)
    final = trajectory.get("final") or {}
    for strength in FINGERPRINT_STRENGTHS:
        matches = [
            index
            for index, step in enumerate(steps)
            if any(position.get(strength) == current[strength] for position in step.get("positions") or [])
        ]
        # The end of the route is one more position: a stash-and-pop cycle or a
        # metadata-only command (mergetool, prune) returns to a state that also
        # looks finished, and history decides which one the learner is at.
        if final.get(strength) == current[strength]:
            matches.append(len(steps))
        if matches:
            return _route_position(steps, matches, history)
    return None


def next_solution_step(
    trajectory: dict | None, state: dict, history: Iterable[str] = ()
) -> dict | None:
    """The next state-changing solution step from ``state``, if it is on route.

    Diagnostic steps (status, log, show) are skipped: they are never the move a
    repository needs next.
    """

    position = route_position(trajectory, state, history)
    if position is None:
        return None
    steps = trajectory["steps"]
    for index in range(position, len(steps)):
        if _is_move(steps[index]):
            return {**steps[index], "index": index}
    return None


def _is_move(step: dict) -> bool:
    return not step.get("diagnostic") and str(step.get("command") or "").startswith("git ")


def _route_position(steps: list[dict], matches: list[int], history: Iterable[str]) -> int:
    """Pick among solution positions that share the learner's repository state.

    A later position is only credited when the learner has run at least as many
    moves of each command family as the route does to reach it; diagnostic-only
    gaps need no evidence.
    """

    executed = Counter(_command_key(command) for command in history)
    earliest = min(matches)
    for index in sorted(matches, reverse=True):
        needed = Counter(_command_key(step["command"]) for step in steps[:index] if _is_move(step))
        if all(executed[key] >= count for key, count in needed.items()):
            return index
    return earliest


def _command_key(command: str) -> str:
    tokens = str(command or "").split()
    return " ".join(tokens[:2])
