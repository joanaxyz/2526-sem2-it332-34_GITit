"""Regenerate ``curriculum/seed_data/generated/generated_targets.py``.

The git command engine lives in the frontend now, so target repository states are
no longer derived in Python. This command collects every module tier, wave and Challenge Gate case's
``initial_state`` + ``solution_commands`` (+ mid-sequence workspace file edits),
replays each through the real browser engine via a small Vite-driven Node script
(``frontend/scripts/generate-targets.mjs``), verifies that every command is
processable within the level budget, and writes the results back as
``TARGET_STATES``. The same replay is fingerprinted into
``SOLUTION_TRAJECTORIES`` (``generated/generated_trajectories.py``), which lets
the runtime tutor tell which solution step a learner's repository is at.

Run after changing any variant's initial state or solution:

    python manage.py generate_targets
"""

from __future__ import annotations

import json
from pathlib import Path

from django.core.management.base import BaseCommand, CommandError

from curriculum.management.commands.seed_curriculum import MODULE_LEVELS
from curriculum.seed_data.source.scenario_fixtures import extension_cases
from curriculum.services.solution_replay import replay_solutions, verify_backend_transitions
from simulator.trajectory import build_solution_trajectory

GENERATED_DIR = Path(__file__).resolve().parents[2] / "seed_data" / "generated"
TARGETS_FILE = GENERATED_DIR / "generated_targets.py"
TRAJECTORIES_FILE = GENERATED_DIR / "generated_trajectories.py"

HEADER = (
    "# Generated by `python manage.py generate_targets`. Do not edit by hand.\n"
    "# Regenerate after changing any variant's initial_state or solution_commands.\n"
    "import json\n\n"
    'TARGET_STATES = json.loads(r"""\n'
)
FOOTER = '\n""")\n'
TRAJECTORY_HEADER = (
    "# Generated by `python manage.py generate_targets`. Do not edit by hand.\n"
    "# Repository fingerprints in front of every solution command; see\n"
    "# simulator/trajectory.py.\n"
    "import json\n\n"
    'SOLUTION_TRAJECTORIES = json.loads(r"""\n'
)


class Command(BaseCommand):
    help = (
        "Validate and replay every seed variant's solution through the frontend git "
        "engine to rebuild generated/generated_targets.py."
    )

    def add_arguments(self, parser) -> None:
        parser.add_argument(
            "--check",
            action="store_true",
            help=(
                "Fail (non-zero) if regeneration would change generated/generated_targets.py, "
                "instead of writing it."
            ),
        )

    def handle(self, *args, **options) -> None:
        cases = self._collect_cases()
        self.stdout.write(f"Collected {len(cases)} variant solutions.")
        targets, replays = self._run_generator(cases)
        missing = sorted(set(cases) - set(targets))
        if missing:
            raise CommandError(f"Generator returned no target for: {', '.join(missing[:10])}")
        rejected = verify_backend_transitions(replays)
        if rejected:
            raise CommandError(
                "The backend would reject these authored routes, so learners could not "
                "solve them:\n" + "\n".join(rejected[:20])
            )
        trajectories = {
            case_id: build_solution_trajectory(replay) for case_id, replay in replays.items()
        }

        outputs = [
            (TARGETS_FILE, self._render(targets, HEADER), f"{len(targets)} target states"),
            (
                TRAJECTORIES_FILE,
                self._render(trajectories, TRAJECTORY_HEADER),
                f"{len(trajectories)} solution trajectories",
            ),
        ]
        if options["check"]:
            for path, rendered, _ in outputs:
                current = path.read_text(encoding="utf-8") if path.exists() else ""
                if current != rendered:
                    raise CommandError(
                        f"generated/{path.name} is stale - run `python manage.py generate_targets`."
                    )
            self.stdout.write(
                self.style.SUCCESS("Generated targets and trajectories are up to date.")
            )
            return

        for path, rendered, summary in outputs:
            path.write_text(rendered, encoding="utf-8")
            relative = path.relative_to(Path(__file__).resolve().parents[2])
            self.stdout.write(self.style.SUCCESS(f"Wrote {summary} to {relative}."))

    def _collect_cases(self) -> dict[str, dict]:
        cases: dict[str, dict] = {}

        def add(variant: dict, *, max_counted_commands: int) -> None:
            case_id = variant.get("case_id")
            if not case_id:
                return
            if case_id in cases:
                raise CommandError(f"Duplicate variant case_id: {case_id!r}")
            cases[case_id] = {
                "initial_state": variant.get("initial_state_template") or {},
                "solution_commands": list(variant.get("solution_commands_template") or []),
                "workspace_files": list(variant.get("solution_workspace_files_template") or []),
                "max_counted_commands": max_counted_commands,
            }

        # Module tiers author their cases inline (no *_template suffix), so
        # normalize the key names the collector reads.
        for level in MODULE_LEVELS:
            for tier in level.get("tiers", {}).values():
                for case in tier.get("cases", []):
                    add(
                        {
                            "case_id": case.get("case_id"),
                            "initial_state_template": case.get("initial_state") or {},
                            "solution_commands_template": case.get("solution_commands") or [],
                            "solution_workspace_files_template": case.get(
                                "solution_workspace_files"
                            )
                            or [],
                        },
                        max_counted_commands=tier.get("max_counted_commands") or 0,
                    )
        # Wave and Challenge Gate scenarios (source/scenario_fixtures/) are live
        # cases too; their budget is the authored maximum.
        for case_id, case in extension_cases().items():
            add(
                {
                    "case_id": case_id,
                    "initial_state_template": case["initial_state"],
                    "solution_commands_template": case["solution_commands"],
                    "solution_workspace_files_template": case["solution_workspace_files"],
                },
                max_counted_commands=case["max_counted_commands"],
            )
        return cases

    def _run_generator(self, cases: dict[str, dict]) -> tuple[dict[str, dict], dict[str, dict]]:
        return replay_solutions(cases)

    def _render(self, data: dict[str, dict], header: str) -> str:
        body = json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False)
        # The payload is embedded in a raw triple-quoted string; valid JSON can
        # never contain `"""`, but guard anyway so a bad payload fails loudly.
        if '"""' in body:
            raise CommandError(
                "Generated JSON contains a triple-quote and cannot be embedded safely."
            )
        return f"{header}{body}{FOOTER}"
